def post_process_sql(sql: str) -> str:
    """Clean and fix SQL generated by Ollama."""
    sql = sql.strip()

    lines = sql.split("\n")
    clean_lines = []
    for line in lines:
        line = line.strip()
        if (
            line.lower().startswith("error:")
            or line.lower().startswith("note:")
            or line.lower().startswith("sorry")
        ):
            continue
        clean_lines.append(line)
    sql = "\n".join(clean_lines).strip()

    if "hitl_approvals" in sql.lower():
        if "select" not in sql.lower():
            sql = "SELECT * FROM hitl_approvals WHERE status = 'pending'"
        elif "amount" in sql.lower():
            sql = re.sub(
                r"\s+AND\s+amount\s*[=<>!]+\s*[\d\.]+", "", sql, flags=re.IGNORECASE
            )
            sql = re.sub(
                r"\s+WHERE\s+amount\s*[=<>!]+\s*[\d\.]+(\s+AND|$)",
                " WHERE ",
                sql,
                flags=re.IGNORECASE,
            )
            sql = re.sub(r"\s+AND\s+AND\s+", " AND ", sql)
            sql = re.sub(r"\s+OR\s+OR\s+", " OR ", sql)
            sql = re.sub(r"\s+WHERE\s+AND\s+", " WHERE ", sql)
            sql = re.sub(r"\s+WHERE\s+OR\s+", " WHERE ", sql)
            sql = re.sub(r"\s+WHERE\s+\s*$", "", sql)
            if sql.strip().upper().endswith("WHERE"):
                sql = sql.strip()[:-5].strip()

    if "select" not in sql.lower():
        if "pending" in sql.lower() or "pending order" in sql.lower():
            sql = "SELECT * FROM orders WHERE status = 'pending'"
        elif "completed" in sql.lower() or "completed order" in sql.lower():
            sql = "SELECT * FROM orders WHERE status = 'completed'"

    sql = sql.rstrip(";").strip()
    if not sql.upper().startswith("SELECT"):
        sql = "SELECT * FROM orders WHERE status = 'completed'"

    return sql


RULES = [
    (
        r"completed.*order|order.*completed",
        "SELECT * FROM orders WHERE status = 'completed'",
    ),
    (
        r"pending.*order|order.*pending",
        "SELECT * FROM orders WHERE status = 'pending'",
    ),
    (
        r"daily.*sales|sales.*report",
        "SELECT * FROM gold_daily_sales ORDER BY date DESC",
    ),
    (
        r"product.*performance|top.*product",
        "SELECT * FROM gold_product_performance ORDER BY total_revenue DESC",
    ),
    (
        r"customer.*360|customer.*segment",
        "SELECT * FROM gold_customer_360 ORDER BY total_spent DESC",
    ),
    (
        r"order.*over.*?(\d+)",
        "SELECT * FROM orders WHERE total_amount > {0}",
    ),
    (
        r"pipeline|process.*data",
        "SELECT * FROM orders WHERE status = 'completed'",
    ),
]


def rule_based_sql(query: str) -> str:
    """Generate SQL using pattern matching rules for e-commerce."""
    q = query.lower()
    for pattern, template in RULES:
        m = re.search(pattern, q)
        if m:
            groups = m.groups()
            if groups:
                try:
                    amount = int(groups[0].replace(",", ""))
                    return template.format(amount)
                except (ValueError, IndexError):
                    pass
            return template

    if "order" in q:
        return "SELECT * FROM orders WHERE status = 'completed'"
    if "product" in q:
        return "SELECT * FROM products"
    if "sales" in q or "revenue" in q:
        return "SELECT * FROM gold_daily_sales ORDER BY date DESC"
    if "customer" in q:
        return "SELECT * FROM gold_customer_360 ORDER BY total_spent DESC"
    if "pipeline" in q or "process" in q:
        return "SELECT * FROM orders WHERE status = 'completed'"
    return "SELECT * FROM orders WHERE status = 'completed'"


