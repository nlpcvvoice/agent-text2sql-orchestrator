def generate_sql_explanation(sql: str, result_data: list, natural_query: str) -> str:
    """Generate explanation of the SQL query result using Ollama."""
    data_summary = f"Found {len(result_data)} rows"
    if result_data:
        sample = result_data[0] if result_data else {}
        data_summary += f". Sample columns: {', '.join(list(sample.keys())[:5])}"

    prompt = f"""Explain this SQL query and its result in plain English:

Original question: {natural_query}
Generated SQL: {sql}
Result: {data_summary}

Keep explanation brief and clear."""

    return call_ollama(prompt, timeout=30)


